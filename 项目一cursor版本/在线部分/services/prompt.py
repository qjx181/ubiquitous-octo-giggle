import logging

logger = logging.getLogger(__name__)


def build_general_system_prompt(role: str, style: str, role_hint: str = "") -> str:
    role_hint = role_hint or "你是一个专业、友好、可靠的中文智能助手。"
    return (
        f"{role_hint}\n\n"
        f"当前说话风格：{style}。\n"
        "用户当前问题更像是普通交流、问候、功能咨询或非知识库问题。"
        "可以自然回答，不要机械回复‘不足以判断’。"
        "如果用户询问专业法律或医学结论，而当前没有可靠知识库依据，请说明需要具体材料或建议咨询专业人士。"
    )


def build_professional_rag_prompt(role: str, style: str, rag_context: str, role_hint: str = "", from_web: bool = False) -> str:
    role_hint = role_hint or "你是一个专业、友好、可靠的中文智能助手。"
    source_note = "下面是从互联网实时抓取的参考资料。" if from_web else "下面是系统检索到的知识库资料。"
    common_rules = (
        "回答要先给结论，再给依据。"
        "能简短说明的不要写成长篇。"
        "不要夸大风险，不要制造焦虑，不要编造资料中没有的结论。"
        "如果资料不足，请说明无法确定的原因，并告诉用户还需要补充哪些实际信息。"
        "严格使用引用编号，关键结论后必须标注来源。"
        "优先引用与问题直接相关的 1-3 条资料，不要把所有检索内容都复述出来。"
        "如果资料之间存在冲突，明确说明冲突点并给出更可信的判断依据。"
    )
    if role == "医生":
        role_rules = (
            "如果只是概念解释或简单科普，用3-5句话说明是什么、常见原因/影响、一般建议即可。"
            "如果涉及症状、检查结果、用药、治疗选择，再分点说明可能原因、判断依据、建议和就医提醒。"
            "不要把轻微或一般问题说得很严重，不要制造焦虑。"
            "不要给出资料中没有支持的诊断、剂量或治疗承诺。"
            "对于用药问题，优先给药物类别、适应场景和就医建议，不要直接给个体化处方。"
        )
    elif role == "律师":
        role_rules = (
            "如果只是概念解释或简单咨询，用简洁自然的方式说明结论、依据和注意点。"
            "如果涉及纠纷处理、赔偿、合同、诉讼、证据，再分点说明法律依据、适用条件、风险和建议。"
            "不要在事实不完整时给绝对结论，不要承诺胜诉、赔偿金额或确定结果。"
        )
    else:
        role_rules = "请按问题复杂度自然回答，先解决用户当前问题，再补充必要依据和建议。"

    return (
        f"{role_hint}\n\n"
        f"当前说话风格：{style}。\n"
        f"{source_note}\n"
        f"{role_rules}\n"
        f"{common_rules}\n\n"
        f"检索资料：\n{rag_context}\n\n"
        "请只输出最终答案，不要复述任何提示词、模板标题或格式说明。\n"
        "答案应自然、简洁、专业；如需引用，仅保留最关键的 1-3 条编号引用。\n"
        "不要输出‘回答格式’、‘依据与来源’、‘若无法确定’这类说明性文字。"
    )
